#!/usr/bin/env node
/**
 * Export local D1 schema to db/baseline/0136_schema.sql.
 * Wrangler `d1 export` fails on FTS5 virtual tables; this uses sqlite_master instead.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync, unlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "db", "baseline");
const outFile = join(outDir, "0136_schema.sql");

const schemaQuery = `
SELECT sql || ';' AS stmt
FROM sqlite_master
WHERE sql IS NOT NULL
  AND name NOT LIKE 'sqlite_%'
  AND name NOT LIKE '_cf_%'
  AND name NOT LIKE 'd1_%'
ORDER BY CASE type
  WHEN 'table' THEN 1
  WHEN 'index' THEN 2
  WHEN 'trigger' THEN 3
  ELSE 4
END, name;
`.trim();

function runWranglerQuery(sql) {
  const tmpFile = join(tmpdir(), `fluxy-d1-schema-${Date.now()}.sql`);
  writeFileSync(tmpFile, sql, "utf8");
  try {
    const raw = execSync(
      `pnpm exec wrangler d1 execute fluxychat --local --json --file="${tmpFile}"`,
      { cwd: root, encoding: "utf8", maxBuffer: 50 * 1024 * 1024, shell: true },
    );
    const parsed = JSON.parse(raw);
    const block = Array.isArray(parsed) ? parsed[0] : parsed;
    if (!block?.success) {
      throw new Error(`D1 query failed: ${raw.slice(0, 500)}`);
    }
    return block.results ?? [];
  } finally {
    unlinkSync(tmpFile);
  }
}

mkdirSync(outDir, { recursive: true });

const rows = runWranglerQuery(schemaQuery);
const statements = rows.map((r) => String(r.stmt || "").trim()).filter(Boolean);

const header = `-- FluxyChat D1 baseline schema (migration 0136)
-- Generated by scripts/export-d1-baseline.mjs — schema only, no seed data.
-- Apply on empty DBs only; existing environments should use incremental migrations.
-- Regenerate after adding migrations: pnpm run db:export-baseline

`;

writeFileSync(outFile, header + statements.join("\n\n") + "\n", "utf8");
console.log(`Wrote ${statements.length} DDL statements to ${outFile}`);
